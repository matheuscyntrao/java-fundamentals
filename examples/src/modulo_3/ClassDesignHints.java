package modulo_3;

public class ClassDesignHints {

    /**
     * Always keep data private
     * Always initialize data
     * Don't use too many basic types in a class
     * Not all fields need individual field accessors and mutators
     * Break up classes that have too many responsibilities (Solid) - Single Responsability
     * Make the names of your classes and methods reflect their responsabilities
     * Prefer immutable classes
     */

}
