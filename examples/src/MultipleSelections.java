import java.util.Scanner;

public class MultipleSelections {

    static void main() {
        Scanner in = new Scanner(System.in);
        System.out.println("Select an option (1, 2, 3, 4)");
        int choice = in.nextInt();

        switch(choice) {
            case 1: break;
            case 2: break;
            case 3: break;
            case 4: break;
            default: break;
        }
    }

}
